const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const pvxRoot = path.join(root, 'pvxcode-master', 'pvxcode-master');
const databaseRoot = path.join(pvxRoot, 'gwbbcode', 'databases');
const imageRoot = path.join(pvxRoot, 'images');
const pconsRoot = path.join(root, 'pcons-tmp');
const titlesRoot = path.join(root, 'titles_tmp');
const dataOut = path.join(root, 'src', 'data');
const staticOut = path.join(root, 'static', 'gwbbcode');

function read(file) {
    return fs.readFileSync(file, 'utf8');
}

function unquotePhp(value) {
    return value
        .replace(/\\\\/g, '\\')
        .replace(/\\'/g, "'")
        .replace(/\\"/g, '"')
        .replace(/\\n/g, '\n')
        .replace(/\\r/g, '\r')
        .replace(/\\t/g, '\t');
}

function parsePhpScalar(value) {
    const trimmed = value.trim();
    const quoted = trimmed.match(/^'((?:\\'|[^'])*)'$/s);

    if (quoted) {
        return unquotePhp(quoted[1]);
    }

    if (/^-?\d+(?:\.\d+)?$/.test(trimmed)) {
        return Number(trimmed);
    }

    return trimmed;
}

function parseSkillDb() {
    const source = read(path.join(databaseRoot, 'skill_db.php'));
    const entries = {};
    const entryMatcher = /(\d+)=>\s*array\s*\(([\s\S]*?)\n\),/g;
    let entry;

    while ((entry = entryMatcher.exec(source)) !== null) {
        const id = Number(entry[1]);
        const body = entry[2];
        const skill = {id};
        const fieldMatcher = /'([^']+)'\s*=>\s*('(?:\\'|[^'])*'|-?\d+(?:\.\d+)?)/g;
        let field;

        while ((field = fieldMatcher.exec(body)) !== null) {
            skill[field[1]] = parsePhpScalar(field[2]);
        }

        entries[id] = skill;
    }

    return entries;
}

function parseNameDb() {
    const source = read(path.join(databaseRoot, 'skillname_db.php'));
    const names = {};
    const matcher = /'((?:\\'|[^'])*)'\s*=>\s*(\d+)/g;
    let match;

    while ((match = matcher.exec(source)) !== null) {
        names[unquotePhp(match[1])] = Number(match[2]);
    }

    return names;
}

function parseAbbrDb() {
    const source = read(path.join(databaseRoot, 'abbr_db.php'));
    const abbreviations = {};
    const matcher = /'((?:\\'|[^'])*)'\s*=>\s*'((?:\\'|[^'])*)'/g;
    let match;

    while ((match = matcher.exec(source)) !== null) {
        abbreviations[unquotePhp(match[1])] = unquotePhp(match[2]);
    }

    return abbreviations;
}

function parsePvpIdsDb() {
    const source = read(path.join(databaseRoot, 'skillpvpids_db.php'));
    const pvpToPve = {};
    const matcher = /(\d+)\s*=>\s*(\d+)/g;
    let match;

    while ((match = matcher.exec(source)) !== null) {
        pvpToPve[match[1]] = Number(match[2]);
    }

    return pvpToPve;
}

function copyDirectory(from, to) {
    fs.mkdirSync(to, {recursive: true});
    for (const entry of fs.readdirSync(from, {withFileTypes: true})) {
        const source = path.join(from, entry.name);
        const target = path.join(to, entry.name);

        if (entry.isDirectory()) {
            copyDirectory(source, target);
        } else if (entry.isFile()) {
            fs.copyFileSync(source, target);
        }
    }
}

function writeGeneratedData() {
    if (!fs.existsSync(path.join(databaseRoot, 'skill_db.php'))) {
        return null;
    }

    fs.mkdirSync(dataOut, {recursive: true});

    const skillsById = parseSkillDb();
    const skillIdsByName = parseNameDb();
    const abbreviations = parseAbbrDb();
    const pvpToPve = parsePvpIdsDb();
    const data = {
        abbreviations,
        pvpToPve,
        skillIdsByName,
        skillsById,
    };

    const contents = [
        '// Generated by tools/generate-gwbbcode-assets.cjs from pvxcode-master.',
        '// Do not edit this file by hand; edit the generator or source data instead.',
        `const gwSkillData = ${JSON.stringify(data, null, 2)};`,
        '',
        'export default gwSkillData;',
        '',
    ].join('\n');

    fs.writeFileSync(path.join(dataOut, 'gwSkillData.js'), contents);
    return Object.keys(skillsById).length;
}

function normalizeItemName(name) {
    return name
        .replace(/\.[^.]+$/, '')
        .replace(/_/g, ' ')
        .trim();
}

function normalizeLookupName(name) {
    return name
        .trim()
        .replace(/['"!]/g, '')
        .replace(/[_-]+/g, ' ')
        .replace(/\s+/g, ' ')
        .toLowerCase();
}

function writeGeneratedConsumables() {
    fs.mkdirSync(dataOut, {recursive: true});

    const consumables = {};
    const consumableIdsByName = {};

    if (!fs.existsSync(pconsRoot)) {
        return 0;
    }

    fs.mkdirSync(path.join(staticOut, 'consumables'), {recursive: true});

    const files = fs.readdirSync(pconsRoot, {withFileTypes: true})
        .filter((entry) => entry.isFile() && /\.(?:png|jpe?g|webp|gif)$/i.test(entry.name))
        .map((entry) => entry.name)
        .sort((a, b) => a.localeCompare(b));

    for (const file of files) {
        const id = file.replace(/\.[^.]+$/, '');
        const name = normalizeItemName(file);
        const image = `/gwbbcode/consumables/${file}`;

        consumables[id] = {
            id,
            image,
            name,
        };
        consumableIdsByName[normalizeLookupName(name)] = id;
        consumableIdsByName[normalizeLookupName(id)] = id;

        fs.copyFileSync(path.join(pconsRoot, file), path.join(staticOut, 'consumables', file));
    }

    const contents = [
        '// Generated by tools/generate-gwbbcode-assets.cjs from pcons-tmp.',
        '// Do not edit this file by hand; edit the generator or source images instead.',
        `const gwConsumableData = ${JSON.stringify({consumableIdsByName, consumables}, null, 2)};`,
        '',
        'export default gwConsumableData;',
        '',
    ].join('\n');

    fs.writeFileSync(path.join(dataOut, 'gwConsumableData.js'), contents);

    return files.length;
}

