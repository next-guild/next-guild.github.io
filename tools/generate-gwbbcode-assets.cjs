function writeStaticAssets() {
    if (!fs.existsSync(imageRoot)) {
        return false;
    }

    copyDirectory(path.join(imageRoot, 'img_skills'), path.join(staticOut, 'skills'));
    copyDirectory(path.join(imageRoot, 'img_thumb'), path.join(staticOut, 'thumbs'));
    return true;
}

const count = writeGeneratedData();
const consumableCount = writeGeneratedConsumables();
const titleCount = writeGeneratedTitles();
const copiedSkillImages = writeStaticAssets();

console.log(count == null ? 'Skipped skill data generation; pvxcode-master source not found.' : `Generated ${count} skills into src/data/gwSkillData.js`);
console.log(`Generated ${consumableCount} consumables into src/data/gwConsumableData.js`);
console.log(`Generated ${titleCount} titles into src/data/gwTitleData.js`);
